-- TIME FUNCTIONS
-- CURTIME()
SELECT CURTIME();
SELECT CURTIME() AS TIMEE;
-- ADDTIME()
SELECT ADDTIME("13:45:45","1:0:0");
SELECT ADDTIME("15:23:0","0:10:0") AS UPDATED_TIME;
-- SUBTIME()
SELECT SUBTIME("13:45:45","1:0:0");
select SUBTIME("15:45:45","0:45:0") AS UPDATED_TIME;
-- TIMEDIFF()
SELECT TIMEDIFF("13:13:13","12:13:13");
SELECT TIMEDIFF("24:0:0","12:0:0") AS UPDATED_TIME;

-- TIMESTAMP
CREATE TABLE T1(
	ID INT,
    TS1 TIMESTAMP
);
INSERT INTO T1 VALUES (1,"2024-12-12 13:0:0");
INSERT INTO T1 VALUES (2,"23:45:4");
INSERT INTO T1 VALUES (3,"2024-4-4");
SELECT * FROM T1;


CREATE TABLE T2(
	ID INT,
